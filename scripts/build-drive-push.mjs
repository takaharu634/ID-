import { build } from 'esbuild';
import { readFile, mkdir, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
const result = await build({ entryPoints: ['integrations/trackman-drive/engine-entry.mjs'], bundle: true, write: false, platform: 'neutral', format: 'iife', globalName: 'TohtoImport', target: 'es2022', minify: true });
const engine = result.outputFiles[0].text;
const client = await readFile('integrations/trackman-drive/client.gs', 'utf8');
const version = createHash('sha256').update(engine).update(client).digest('hex');
const source = client.replaceAll('__ENGINE_VERSION__', version) + '\n' + engine;
await mkdir('server/generated', { recursive: true });
await writeFile('server/generated/drive-push-script.mjs', `// Generated by scripts/build-drive-push.mjs. No credentials.\nexport const engineVersion = ${JSON.stringify(version)};\nexport const scriptTemplate = ${JSON.stringify(source)};\n`);
console.log(`Drive push script: ${Buffer.byteLength(source)} bytes; engine ${version.slice(0, 12)}`);
