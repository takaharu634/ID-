export const OFFICIAL_BATTING_SOURCE = "東都大学野球連盟 2026年春季リーグ 個人成績（ユーザー提供表）";

const key = (team, kanji) => `${team}|${String(kanji).replace(/[\s　]/g, "").replace(/高/g, "髙")}`;

export function applyOfficialBatting2026Spring(batters, season = "") {
  if (!String(season).includes("2026") || !String(season).includes("春")) {
    return { matched: 0, changed: 0 };
  }
  const records = new Map(OFFICIAL_BATTING_2026_SPRING.map((row) => [key(row.team, row.kanji), row]));
  let matched = 0;
  let changed = 0;
  for (const batter of batters) {
    const official = records.get(key(batter.team, batter.kanji));
    if (!official) continue;
    matched += 1;
    const trackman = {
      pa: batter.pa, ab: batter.ab, hits: batter.hits, doubles: batter.doubles,
      triples: batter.triples, homeRuns: batter.homeRuns, strikeouts: batter.strikeouts,
      battingAverage: batter.battingAverage,
    };
    if (["pa", "ab", "hits", "doubles", "triples", "homeRuns", "strikeouts"]
      .some((field) => trackman[field] !== official[field])) changed += 1;
    Object.assign(batter, official, {
      singles: official.hits - official.doubles - official.triples - official.homeRuns,
      sluggingPercentage: Number((official.totalBases / official.ab).toFixed(3)),
      officialRecord: true,
      officialSource: OFFICIAL_BATTING_SOURCE,
      trackmanRecord: trackman,
    });
  }
  return { matched, changed };
}
